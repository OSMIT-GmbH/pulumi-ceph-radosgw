func (Key) Delete(ctx context.Context, req infer.DeleteRequest[KeyState]) (infer.DeleteResponse, error) {
	p.GetLogger(ctx).Infof("DELETE on %s[%s]: Keeping as this object was assimilated!", "Key", req.ID)
	ce, c, err := initClient(ctx)
	if err != nil {
		return infer.DeleteResponse{}, err
	}
	if req.State.Assimilated && !c.deleteAssimilated {
		p.GetLogger(ctx).Infof("DELETE on %s[%s]: Keeping as this object was assimilated!", "Key", req.ID)
		return infer.DeleteResponse{}, nil
	}

	return infer.DeleteResponse{}, ce.client.RemoveKey(ctx, admin.UserKeySpec{
		UID:       req.State.UserID,
		SubUser:   req.State.SubUserName,
		AccessKey: req.State.AccessKey,
		KeyType:   req.State.KeyType,
	})
}
